using UnityEngine;

namespace Arrows.Spline
{
    /// <summary>
    /// Static utility for evaluating Catmull-Rom spline segments.
    /// A Catmull-Rom spline interpolates between p1 and p2 given four control points
    /// (p0, p1, p2, p3), producing a C1-continuous curve that passes through all interior points.
    /// </summary>
    public static class CatmullRomSpline
    {
        /// <summary>
        /// Evaluates position on a Catmull-Rom spline segment defined by 4 control points.
        /// Interpolates between p1 and p2 at parameter t ∈ [0, 1].
        /// </summary>
        public static Vector2 Evaluate(Vector2 p0, Vector2 p1, Vector2 p2, Vector2 p3, float t)
        {
            float t2 = t * t;
            float t3 = t2 * t;

            // Standard Catmull-Rom matrix form
            return 0.5f * (
                (2f * p1) +
                (-p0 + p2) * t +
                (2f * p0 - 5f * p1 + 4f * p2 - p3) * t2 +
                (-p0 + 3f * p1 - 3f * p2 + p3) * t3
            );
        }

        /// <summary>
        /// Evaluates the first derivative (tangent) on a Catmull-Rom spline segment.
        /// The tangent direction at parameter t, NOT normalized.
        /// </summary>
        public static Vector2 EvaluateTangent(Vector2 p0, Vector2 p1, Vector2 p2, Vector2 p3, float t)
        {
            float t2 = t * t;

            return 0.5f * (
                (-p0 + p2) +
                (4f * p0 - 10f * p1 + 8f * p2 - 2f * p3) * t +
                (-3f * p0 + 9f * p1 - 9f * p2 + 3f * p3) * t2
            );
        }

        /// <summary>
        /// Evaluates a Catmull-Rom spline at global parameter t ∈ [0,1] over an array of
        /// control points. The path passes through ALL control points. Virtual endpoint
        /// control points are generated by mirroring.
        /// </summary>
        /// <param name="controlPoints">Array of at least 2 control points.</param>
        /// <param name="t">Global parameter from 0 (first point) to 1 (last point).</param>
        public static Vector2 EvaluatePath(Vector2[] controlPoints, float t)
        {
            int segmentCount = controlPoints.Length - 1;
            t = Mathf.Clamp01(t);

            float segmentFloat = t * segmentCount;
            int segment = Mathf.Min((int)segmentFloat, segmentCount - 1);
            float localT = segmentFloat - segment;

            Vector2 p0 = GetPoint(controlPoints, segment - 1);
            Vector2 p1 = controlPoints[segment];
            Vector2 p2 = controlPoints[segment + 1];
            Vector2 p3 = GetPoint(controlPoints, segment + 2);

            return Evaluate(p0, p1, p2, p3, localT);
        }

        /// <summary>
        /// Evaluates tangent at global parameter t over an array of control points.
        /// </summary>
        public static Vector2 EvaluatePathTangent(Vector2[] controlPoints, float t)
        {
            int segmentCount = controlPoints.Length - 1;
            t = Mathf.Clamp01(t);

            float segmentFloat = t * segmentCount;
            int segment = Mathf.Min((int)segmentFloat, segmentCount - 1);
            float localT = segmentFloat - segment;

            Vector2 p0 = GetPoint(controlPoints, segment - 1);
            Vector2 p1 = controlPoints[segment];
            Vector2 p2 = controlPoints[segment + 1];
            Vector2 p3 = GetPoint(controlPoints, segment + 2);

            return EvaluateTangent(p0, p1, p2, p3, localT);
        }

        /// <summary>
        /// Returns the control point at the given index, with virtual mirrored points
        /// at indices below 0 or beyond the array.
        /// </summary>
        private static Vector2 GetPoint(Vector2[] points, int index)
        {
            if (index < 0)
                return 2f * points[0] - points[1];
            if (index >= points.Length)
                return 2f * points[points.Length - 1] - points[points.Length - 2];
            return points[index];
        }
    }
}

